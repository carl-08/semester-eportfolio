import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
from sklearn.linear_model import LinearRegression
from sklearn import metrics
from sklearn.feature_selection import RFE
from sklearn.impute import SimpleImputer # Import SimpleImputer

# Assuming X_numerical and y are already defined from previous cells

# Impute missing values in X_numerical before RFE
imputer = SimpleImputer(strategy='median')
# Fit and transform X_numerical, then convert back to DataFrame to retain column names
# Store column names first, as fit_transform returns a NumPy array
numerical_cols = X_numerical.columns
X_numerical_imputed = imputer.fit_transform(X_numerical)
X_numerical_imputed_df = pd.DataFrame(X_numerical_imputed, columns=numerical_cols)


# 1. Perform RFE to get feature rankings
estimator = LinearRegression()
# Use the imputed DataFrame for RFE
rfe = RFE(estimator=estimator, n_features_to_select=8) # Select 8 features, as per X_numerical columns
rfe.fit(X_numerical_imputed_df, y)

# Create a DataFrame for RFE ranking
rfe_ranking = pd.DataFrame({
    'Feature': X_numerical_imputed_df.columns, # Use the imputed DataFrame's columns
    'Rank': rfe.ranking_, # Corrected from rfe.rankings_ to rfe.ranking_
    'Selected': rfe.support_
})

# 2. Identify RFE-selected features
# Based on the previous RFE output, selected features have rank 1
rfe_selected = rfe_ranking[rfe_ranking['Rank'] == 1]['Feature'].tolist()

print(f'RFE Selected Features: {rfe_selected}')

# 2. Create a new dataset (X_rfe_df) with only these selected features
X_rfe_df = X_numerical_imputed_df[rfe_selected]

# 3. Rescale the new dataset using the same MinMaxScaler
scaled_rfe = MinMaxScaler(feature_range=(0, 1))
rescaled_rfe = scaled_rfe.fit_transform(X_rfe_df)

# 4. Split the new dataset into training and testing sets (consistent with original split)
X_train_rfe, X_test_rfe, y_train_rfe, y_test_rfe = train_test_split(
    rescaled_rfe, y,
    test_size=0.30,
    random_state=0
)

from sklearn.impute import SimpleImputer

# Re-impute missing values in X_train_rfe and X_test_rfe just in case
# This step is added as a safeguard against any lingering NaNs,
# especially after scaling, as sklearn estimators don't handle them by default.
imputer_final = SimpleImputer(strategy='median')

X_train_rfe_imputed = imputer_final.fit_transform(X_train_rfe)
X_test_rfe_imputed = imputer_final.transform(X_test_rfe)

# 5. Train a new Linear Regression model on the RFE-selected features
regressor_rfe = LinearRegression()
regressor_rfe.fit(X_train_rfe_imputed, y_train_rfe)

# 6. Make predictions with the new model
y_pred_rfe = regressor_rfe.predict(X_test_rfe_imputed)

# 7. Compare the results
mae_rfe = metrics.mean_absolute_error(y_test_rfe, y_pred_rfe)
mse_rfe = metrics.mean_squared_error(y_test_rfe, y_pred_rfe)
rmse_rfe = np.sqrt(mse_rfe)
r2_rfe = metrics.r2_score(y_test_rfe, y_pred_rfe)

print(f'MAE(RFE): {mae_rfe:.2f}')
print(f'MSE(RFE): {mse_rfe:.2f}')
print(f'RMSE(RFE): {rmse_rfe:.2f}')
print(f'R2 SCORE(RFE): {r2_rfe:.2f}')